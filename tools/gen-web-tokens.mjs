#!/usr/bin/env node
// The desktop's visual tokens, turned into CSS custom properties for the web page.
//
//     node tools/gen-web-tokens.mjs            # writes editor-web/tokens.css
//     node tools/gen-web-tokens.mjs --check    # fails if the committed file is stale
//
// docs/design-tokens.json is exported from the RUNNING desktop by
// editor-godot/design_tokens.gd, and docs/design-status.md names it authoritative for
// visual values. The web page had drifted exactly the way that file predicts a second
// implementation will: a hand-picked #14161a for a canvas the desktop paints #0f1318, an
// accent eyeballed to #6ee7b7 against the desktop's #57e3b4, and audio cables drawn white
// where the whole cable pass settled on mint. Nobody chose any of that; it accreted.
//
// So the CSS is generated and committed, and `--check` sits in the ctest suite next to
// web_onboarding_matches_its_patch: change the desktop palette without regenerating and
// the gate says so, the same way it says so when the tour and its patch disagree.
//
// WHAT THIS EMITS AND WHAT IT REFUSES TO. Values only — colours, spacing, radii, type
// sizes. The knockout, the focus suppression, the LOD ladder and the glyph grammar are
// rules about *when*, they live in docs/graph-node-system.md and docs/graph-cable-system.md,
// and a token file that pretended to carry them would be a second specification. The one
// derived colour (--accent-dim) is written as a color-mix() OF tokens rather than a hex,
// so even the derivation cannot drift.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'docs', 'design-tokens.json'), 'utf8'));
const out = join(root, 'editor-web', 'tokens.css');

const lab = tokens.palettes[tokens.default_palette];

const lines = [];
lines.push('/* GENERATED by tools/gen-web-tokens.mjs from docs/design-tokens.json.');
lines.push(' * Do not edit — edit the desktop, re-export, regenerate. The desktop is the');
lines.push(' * reference implementation and this file is how the web agrees with it. */');
lines.push(':root {');

const emit = (name, value) => lines.push(`    ${name}: ${value};`);

// ---- the raw tokens, named for what the desktop calls them -------------------------
lab.surfaces.forEach((c, i) => emit(`--sg-surface-${i}`, c));
lab.borders.forEach((c, i) => emit(`--sg-border-${i}`, c));
for (const [k, v] of Object.entries(lab.ink)) emit(`--sg-ink-${k}`, v);
emit('--sg-accent', lab.accent);
emit('--sg-on-accent', lab.on_accent);
emit('--sg-focus', lab.focus);
emit('--sg-boundary', lab.boundary);
for (const [k, v] of Object.entries(lab.signal)) emit(`--sg-signal-${k}`, v);
for (const [k, v] of Object.entries(lab.state)) emit(`--sg-${k}`, v);
for (const [k, v] of Object.entries(lab.keys)) emit(`--sg-key-${k.replace('_', '-')}`, v);
for (const [k, v] of Object.entries(tokens.space)) emit(`--sg-space-${k}`, `${v}px`);
for (const [k, v] of Object.entries(tokens.radius)) emit(`--sg-radius-${k}`, `${v}px`);
for (const [k, v] of Object.entries(tokens.type.sizes))
    emit(`--sg-size-${k.replace('_', '-')}`, `${v}px`);

// ---- the page's own vocabulary, mapped rather than re-typed ------------------------
// style.css keeps its semantic names; this block is loaded after its :root and wins.
emit('--bg', 'var(--sg-surface-0)');
emit('--panel', 'var(--sg-surface-1)');
emit('--panel-2', 'var(--sg-surface-2)');
emit('--line', 'var(--sg-border-1)');
emit('--text', 'var(--sg-ink-normal)');
emit('--muted', 'var(--sg-ink-second)');
emit('--accent', 'var(--sg-accent)');
emit('--accent-dim', 'color-mix(in srgb, var(--sg-accent) 32%, var(--sg-surface-1))');
emit('--error', 'var(--sg-error)');
emit('--warning', 'var(--sg-warning)');

lines.push('}');
lines.push('');

const css = lines.join('\n');

if (process.argv.includes('--check')) {
    let committed = '';
    try { committed = readFileSync(out, 'utf8'); } catch { /* missing counts as stale */ }
    if (committed !== css) {
        console.error('editor-web/tokens.css is stale against docs/design-tokens.json.');
        console.error('  regenerate: node tools/gen-web-tokens.mjs');
        process.exit(1);
    }
    console.log('tokens.css matches the desktop export');
} else {
    writeFileSync(out, css);
    console.log(`wrote ${out} — ${lines.length - 2} custom properties from palette "${tokens.default_palette}"`);
}
